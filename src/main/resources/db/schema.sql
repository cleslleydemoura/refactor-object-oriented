CREATE TABLE IF NOT EXISTS item_midia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(TRIM(titulo)) > 0),
    autor_diretor VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(TRIM(autor_diretor)) > 0),
    ano_lancamento INTEGER NOT NULL CHECK (ano_lancamento BETWEEN 1 AND 9999),
    genero VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(genero)) > 0),
    sinopse VARCHAR(2000) NOT NULL CHECK (CHAR_LENGTH(TRIM(sinopse)) > 0),
    tipo_midia VARCHAR(10) NOT NULL CHECK (tipo_midia IN ('LIVRO', 'FILME', 'SERIE'))
);
